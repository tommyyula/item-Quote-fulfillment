def charges_for(category_id):
    """simple-charge dicts for model_v3.simple(...) style lists, in sheet order."""
    out = []
    for cid, cat, tier, std, fmt, d, lo, hi, basis, _note, en, *_ in ITEMS:
        if cat != category_id:
            continue
        out.append({"id": cid, "kind": "simple", "name": en[0], "desc": en[1], "unit": en[2], "default": d, "lo": lo, "hi": hi,
                    "basis": basis, "channel": "Both", "tier": tier, "pct": fmt == "pct", "num": fmt == "num", "new": True, "codes": []})
    return out


