def translations():
    """{lang: {english: translated}} for names, descriptions, units, categories and proposal sections."""
    out = {"zh": {}, "ja": {}, "es": {}}
    for i in ITEMS:
        for lang, tr in zip(("zh", "ja", "es"), i[11:14]):
            for en, x in zip(i[10], tr):
                out[lang][en] = x
    for c in NEW_CATEGORIES:
        for lang, (name, desc) in c["i18n"].items():
            out[lang][c["name"]] = name
            out[lang][c["desc"]] = desc
    for s in NEW_SECTIONS:
        for lang, (label, note) in s["i18n"].items():
            out[lang][s["label"]] = label
            if s["note"]:
                out[lang][s["note"]] = note
    return out
